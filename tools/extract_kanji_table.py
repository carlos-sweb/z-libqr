import sys
import os
import re
import base64
import hashlib
import argparse

DEFAULT_SOURCES = [
    "scratch/refs/nayuki__QR-Code-generator/java/src/main/java/io/nayuki/qrcodegen/QrSegmentAdvanced.java",
    "/home/sweb/.gemini/antigravity-cli/brain/c3d125df-aac2-4820-846d-82cc562a7c29/scratch/refs/nayuki__QR-Code-generator/java/src/main/java/io/nayuki/qrcodegen/QrSegmentAdvanced.java",
    "../QR-Code-generator/java/src/main/java/io/nayuki/qrcodegen/QrSegmentAdvanced.java",
    "../../QR-Code-generator/java/src/main/java/io/nayuki/qrcodegen/QrSegmentAdvanced.java",
]

def find_source(provided_path):
    if provided_path and os.path.isfile(provided_path):
        return provided_path
    for p in DEFAULT_SOURCES:
        if os.path.isfile(p):
            return p
    raise FileNotFoundError(
        "Could not find QrSegmentAdvanced.java. Please provide --source path/to/QrSegmentAdvanced.java\n"
        "Requires a clone of nayuki/QR-Code-generator."
    )

def extract_table(java_path):
    with open(java_path, "r", encoding="utf-8") as f:
        content = f.read()

    start_token = "PACKED_QR_KANJI_TO_UNICODE ="
    end_token = "private static short[] UNICODE_TO_QR_KANJI"

    start = content.find(start_token)
    if start == -1:
        raise ValueError(f"Could not find '{start_token}' in {java_path}")
    end = content.find(end_token, start)
    if end == -1:
        raise ValueError(f"Could not find '{end_token}' in {java_path}")

    section = content[start:end]
    string_literals = re.findall(r'\"([^\"]*)\"', section)
    if not string_literals:
        raise ValueError("No string literals found in PACKED_QR_KANJI_TO_UNICODE definition")

    b64_str = "".join(string_literals)
    raw_bytes = base64.b64decode(b64_str)

    if len(raw_bytes) % 2 != 0:
        raise ValueError(f"Raw byte length ({len(raw_bytes)}) is not even")

    mappings = []  # list of (unicode_cp, qr_kanji_val)
    for i in range(0, len(raw_bytes), 2):
        cp = (raw_bytes[i] << 8) | raw_bytes[i + 1]
        qr_val = i // 2
        if cp != 0xFFFF:
            mappings.append((cp, qr_val))

    return mappings

def generate_zig_file(mappings, output_path):
    # Sort strictly by Unicode codepoint ascending for binary search
    mappings.sort(key=lambda item: item[0])

    num_entries = len(mappings)
    if num_entries != 6879:
        raise ValueError(f"Expected 6879 mappings, got {num_entries}")

    # Validate properties
    for i in range(num_entries):
        cp, qr_val = mappings[i]
        if qr_val < 0 or qr_val >= 8192:
            raise ValueError(f"Entry {i} has invalid qr_kanji_val: {qr_val} (must be in 0..8191)")
        if i > 0:
            prev_cp = mappings[i - 1][0]
            if cp <= prev_cp:
                raise ValueError(f"Non-strictly increasing codepoints: U+{prev_cp:04X} >= U+{cp:04X}")

    lines = []
    lines.append("//! Precomputed lookup table for UTF-8 / Unicode codepoint to 13-bit QR Kanji mode value.")
    lines.append("//!")
    lines.append("//! Automatically generated by `tools/extract_kanji_table.py`.")
    lines.append("//! Source: Project Nayuki's QR Code generator library (io.nayuki.qrcodegen.QrSegmentAdvanced)")
    lines.append("//! Data derived from: JIS X 0208 / ftp://ftp.unicode.org/Public/MAPPINGS/OBSOLETE/EASTASIA/JIS/SHIFTJIS.TXT")
    lines.append("//!")
    lines.append("//! Copyright (c) Project Nayuki. (MIT License)")
    lines.append("//! https://www.nayuki.io/page/qr-code-generator-library")
    lines.append("//! https://github.com/nayuki/QR-Code-generator")
    lines.append("//!")
    lines.append("//! Permission is hereby granted, free of charge, to any person obtaining a copy of")
    lines.append("//! this software and associated documentation files (the \"Software\"), to deal in")
    lines.append("//! the Software without restriction, including without limitation the rights to")
    lines.append("//! use, copy, modify, merge, publish, distribute, sublicense, and/or sell copies of")
    lines.append("//! the Software, and to permit persons to whom the Software is furnished to do so,")
    lines.append("//! subject to the following conditions:")
    lines.append("//! - The above copyright notice and this permission notice shall be included in")
    lines.append("//!   all copies or substantial portions of the Software.")
    lines.append("//! - The Software is provided \"as is\", without warranty of any kind, express or")
    lines.append("//!   implied, including but not limited to the warranties of merchantability,")
    lines.append("//!   fitness for a particular purpose and noninfringement. In no event shall the")
    lines.append("//!   authors or copyright holders be liable for any claim, damages or other")
    lines.append("//!   liability, whether in an action of contract, tort or otherwise, arising from,")
    lines.append("//!   out of or in connection with the Software or the use or other dealings in the Software.")
    lines.append("")
    lines.append("const std = @import(\"std\");")
    lines.append("")
    lines.append("/// Total number of JIS X 0208 characters representable in QR Kanji mode.")
    lines.append("pub const ENTRY_COUNT: usize = 6879;")
    lines.append("")
    lines.append("/// Unpacks the Unicode codepoint from a packed table entry.")
    lines.append("pub inline fn getUnicode(entry: u32) u21 {")
    lines.append("    return @intCast(entry >> 13);")
    lines.append("}")
    lines.append("")
    lines.append("/// Unpacks the 13-bit QR Kanji value from a packed table entry.")
    lines.append("pub inline fn getQrKanji(entry: u32) u13 {")
    lines.append("    return @truncate(entry);")
    lines.append("}")
    lines.append("")
    lines.append("/// Packs a Unicode codepoint and 13-bit QR Kanji value into a single u32 entry.")
    lines.append("pub inline fn pack(cp: u21, qr_val: u13) u32 {")
    lines.append("    return (@as(u32, cp) << 13) | @as(u32, qr_val);")
    lines.append("}")
    lines.append("")
    lines.append("/// Packed table of JIS X 0208 Unicode -> QR Kanji mappings.")
    lines.append("/// Stored in strictly increasing order of Unicode codepoint for O(log N) binary search.")
    lines.append("/// Memory footprint: exactly 6879 * 4 = 27,516 bytes (26.87 KiB) in .rodata, 0 RAM, 0 stack.")
    lines.append("pub const unicode_to_qr_kanji: [ENTRY_COUNT]u32 = [_]u32{")

    # Format entries 8 per line as clean hex literals
    for chunk_start in range(0, num_entries, 8):
        chunk = mappings[chunk_start : chunk_start + 8]
        items = [f"0x{((cp << 13) | qr_val):08X}" for cp, qr_val in chunk]
        lines.append("    " + ", ".join(items) + ",")

    lines.append("};")
    lines.append("")
    lines.append("test \"kanji_table properties\" {")
    lines.append("    try std.testing.expectEqual(@as(usize, ENTRY_COUNT), unicode_to_qr_kanji.len);")
    lines.append("    try std.testing.expectEqual(@as(usize, 27516), @sizeOf(@TypeOf(unicode_to_qr_kanji)));")
    lines.append("    var prev_cp: u21 = 0;")
    lines.append("    for (unicode_to_qr_kanji, 0..) |entry, i| {")
    lines.append("        const cp = getUnicode(entry);")
    lines.append("        const qr = getQrKanji(entry);")
    lines.append("        try std.testing.expect(qr < 8192);")
    lines.append("        if (i > 0) {")
    lines.append("            try std.testing.expect(cp > prev_cp);")
    lines.append("        }")
    lines.append("        try std.testing.expectEqual(entry, pack(cp, qr));")
    lines.append("        prev_cp = cp;")
    lines.append("    }")
    lines.append("}")
    lines.append("")

    content = "\n".join(lines)
    os.makedirs(os.path.dirname(os.path.abspath(output_path)), exist_ok=True)
    with open(output_path, "w", encoding="utf-8") as f:
        f.write(content)

    sha256 = hashlib.sha256(content.encode("utf-8")).hexdigest()
    return num_entries, sha256

def main():
    parser = argparse.ArgumentParser(description="Extract QR Kanji table from QrSegmentAdvanced.java")
    parser.add_argument("--source", default=None, help="Path to QrSegmentAdvanced.java")
    parser.add_argument("--output", default="src/kanji_table.zig", help="Path to generated kanji_table.zig")
    args = parser.parse_args()

    source_path = find_source(args.source)
    print(f"Reading source: {source_path}")
    mappings = extract_table(source_path)
    count, sha256 = generate_zig_file(mappings, args.output)

    print(f"Generated: {args.output}")
    print(f"Total entries: {count}")
    print(f"SHA-256: {sha256}")
    print(f"First 5 entries:")
    for cp, qr_val in mappings[:5]:
        print(f"  U+{cp:04X} -> 0x{qr_val:04X} (packed: 0x{(cp<<13)|qr_val:08X})")
    print(f"Last 5 entries:")
    for cp, qr_val in mappings[-5:]:
        print(f"  U+{cp:04X} -> 0x{qr_val:04X} (packed: 0x{(cp<<13)|qr_val:08X})")

if __name__ == "__main__":
    main()
